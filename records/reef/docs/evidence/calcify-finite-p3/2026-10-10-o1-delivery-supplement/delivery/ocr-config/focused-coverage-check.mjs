import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
const root = process.cwd();
const fixture = JSON.parse(await readFile(`${root}/.planning/ocr-config-delivery/hosted-selection-fixture.json`, 'utf8'));
const rule = JSON.parse(await readFile(`${root}/.opencodereview/rule.json`, 'utf8'));
const baselineRule = JSON.parse(execFileSync('git', ['show', `${fixture.trustedMaster}:.opencodereview/rule.json`], {encoding:'utf8'}));
const workflow = await readFile(`${root}/.github/workflows/open-code-review-pilot.yml`, 'utf8');
const baselineWorkflow = execFileSync('git', ['show', `${fixture.trustedMaster}:.github/workflows/open-code-review-pilot.yml`], {encoding:'utf8'});
assert.equal(workflow, baselineWorkflow.replace("max_tokens_budget: '500000'", "max_tokens_budget: '1500000'"));
assert.deepEqual(rule.include, baselineRule.include);
assert.deepEqual(rule.rules, baselineRule.rules);
assert.deepEqual(rule.exclude, [...baselineRule.exclude, 'services/platform-runtime/src/main/java/reef/contracts/calcify/v1/**']);
const matches = (pattern, path) => new Bun.Glob(pattern.toLowerCase()).match(path.toLowerCase());
const excluded = fixture.beforeSelected.filter(path => rule.exclude.some(pattern => matches(pattern,path))).sort();
const retained = fixture.beforeSelected.filter(path => !excluded.includes(path)).sort();
assert.deepEqual(excluded, fixture.proposedExcludedGeneratedJava);
assert.deepEqual(retained, fixture.afterExpectedSelected);
assert.equal(retained.length,17); assert.equal(excluded.length,31);
const tests = retained.filter(path => path.endsWith('_test.go') || path.includes('/src/test/'));
assert.equal(tests.length,7);
for (const path of tests) assert.ok(rule.include.some(pattern => matches(pattern,path)), `${path}: test include bypass lost`);
for (const path of fixture.beforeSelected) assert.ok(!baselineRule.exclude.some(pattern => matches(pattern,path)));
const result = {beforeSelected:48,afterExpectedSelected:retained.length,generatedJavaExcluded:excluded.length,testIncludesPreserved:tests.length,workflowOnlyBudgetChanged:true,trustAndPinsUnchanged:true,retained,excluded};
await writeFile(`${root}/.planning/ocr-config-delivery/focused-coverage-result.json`, JSON.stringify(result,null,2)+'\n');
console.log('Exact48→17 selection;31 generated excluded;7 test includes preserved; workflow byte comparison PASS');
